// Regenerates lib/pdf/print-page-css.generated.ts: the CSS the app serves to
// the browser print pages (app/globals.css compiled by Tailwind), limited to
// the classes used by components/documents. The emailed PDFs render those
// components with this CSS, so they look the same as the print pages.
//
// Run after changing classes in components/documents or app/globals.css:
//   node scripts/build-print-css.mjs
// (lib/pdf/__tests__/print-page-css.test.ts fails while it is out of date.)

import { readFile, readdir, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { compile, optimize } from '@tailwindcss/node'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const OUT = path.join(root, 'lib/pdf/print-page-css.generated.ts')

// The root layout's <html> and <body> classes (app/layout.tsx), which every
// print page sits inside. Mirrored by lib/pdf/render-print-document.tsx.
export const LAYOUT_CLASSES = ['h-full', 'antialiased', 'min-h-full', 'flex', 'flex-col']

async function sourceFiles(dir) {
  const entries = await readdir(dir, { withFileTypes: true })
  const files = await Promise.all(entries.map(e => {
    const full = path.join(dir, e.name)
    return e.isDirectory() ? sourceFiles(full) : /\.tsx?$/.test(e.name) ? [full] : []
  }))
  return files.flat()
}

/** Every token in a className string literal (static or template) in the document components. */
export async function documentClassCandidates() {
  const candidates = new Set(LAYOUT_CLASSES)
  for (const file of await sourceFiles(path.join(root, 'components/documents'))) {
    const src = await readFile(file, 'utf8')
    for (const m of src.matchAll(/className=(?:"([^"]*)"|\{`([^`]*)`\}|\{'([^']*)'\})/g)) {
      for (const token of (m[1] ?? m[2] ?? m[3]).split(/\s+/)) {
        if (token && !token.includes('${')) candidates.add(token)
      }
    }
  }
  return [...candidates].sort()
}

export async function buildPrintCss() {
  const globalsPath = path.join(root, 'app/globals.css')
  const compiler = await compile(await readFile(globalsPath, 'utf8'), {
    base: path.dirname(globalsPath),
    onDependency: () => {},
  })
  const candidates = await documentClassCandidates()
  const { code } = optimize(compiler.build(candidates), { minify: true })
  return { css: code, candidates }
}

export function moduleSource(css, candidates) {
  return [
    '// GENERATED by scripts/build-print-css.mjs — do not edit by hand.',
    '// app/globals.css compiled by Tailwind for the classes used in components/documents.',
    '',
    `export const PRINT_PAGE_CLASSES: readonly string[] = ${JSON.stringify(candidates)}`,
    '',
    `export const PRINT_PAGE_CSS = ${JSON.stringify(css)}`,
    '',
  ].join('\n')
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const { css, candidates } = await buildPrintCss()
  await writeFile(OUT, moduleSource(css, candidates))
  console.log(`Wrote ${path.relative(root, OUT)}: ${candidates.length} classes, ${css.length} bytes of CSS`)
}
